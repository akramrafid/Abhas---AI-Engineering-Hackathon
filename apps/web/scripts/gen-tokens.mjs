#!/usr/bin/env node
// Deterministic token generator: reads ../../docs/brand/tokens.json (relative to apps/web/)
// and writes apps/web/src/styles/tokens.css with CSS variables, Tailwind v4 @theme inline, and .tnum.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const webDir = path.resolve(scriptDir, "..");
const tokensPath = path.resolve(webDir, "../../docs/brand/tokens.json");
const outPath = path.resolve(webDir, "src/styles/tokens.css");

const tokens = JSON.parse(fs.readFileSync(tokensPath, "utf8"));

const lines = [
  `/* AUTO-GENERATED by apps/web/scripts/gen-tokens.mjs from docs/brand/tokens.json (v${tokens.version}). Do not edit by hand. */`,
  "",
  ":root {",
];

const seenColors = new Set();
const themeColorNames = [];

function pushColorVar(name, value) {
  if (seenColors.has(name)) return;
  seenColors.add(name);
  themeColorNames.push(name);
  lines.push(`  --color-${name}: ${value};`);
}

for (const [key, entry] of Object.entries(tokens.color.brand)) {
  pushColorVar(key, entry.value);
}

for (const [key, entry] of Object.entries(tokens.color.neutral)) {
  pushColorVar(key, entry.value);
}

const riskKeyMap = {
  lowCellBorder: "risk-low-border",
  forecastBand: "forecast-band",
};

for (const [key, entry] of Object.entries(tokens.color.risk)) {
  if (key in riskKeyMap) {
    pushColorVar(riskKeyMap[key], entry.value);
    continue;
  }
  pushColorVar(`risk-${key}`, entry.value);
  if (entry.on) {
    pushColorVar(`risk-${key}-on`, entry.on);
  }
}

lines.push(`  --gradient-signal: ${tokens.color.gradient.signal};`);
lines.push(
  `  --font-sans: "${tokens.font.sans.family}", "${tokens.font.bangla.family}", ${tokens.font.sans.fallback};`,
);
lines.push(`  --font-mono: "${tokens.font.mono.family}", ${tokens.font.mono.fallback};`);
lines.push(`  --font-bangla: "${tokens.font.bangla.family}", ${tokens.font.bangla.fallback};`);

for (const [key, spec] of Object.entries(tokens.type)) {
  lines.push(`  --type-${key}-size: ${spec.size}px;`);
  lines.push(`  --type-${key}-line: ${spec.line}px;`);
  lines.push(`  --type-${key}-weight: ${spec.weight};`);
}

for (const [key, px] of Object.entries(tokens.radius)) {
  lines.push(`  --radius-${key}: ${px}px;`);
}

tokens.space.forEach((px, index) => {
  lines.push(`  --space-${index + 1}: ${px}px;`);
});

lines.push("}");
lines.push("");
lines.push("@theme inline {");

for (const name of themeColorNames) {
  lines.push(`  --color-${name}: var(--color-${name});`);
}

lines.push("  --font-sans: var(--font-sans);");
lines.push("  --font-mono: var(--font-mono);");
lines.push("  --font-bangla: var(--font-bangla);");

for (const key of Object.keys(tokens.radius)) {
  lines.push(`  --radius-${key}: var(--radius-${key});`);
}

for (const key of Object.keys(tokens.type)) {
  lines.push(`  --text-${key}: var(--type-${key}-size);`);
  lines.push(`  --text-${key}--line-height: var(--type-${key}-line);`);
  lines.push(`  --text-${key}--font-weight: var(--type-${key}-weight);`);
}

lines.push("}");
lines.push("");
lines.push(".tnum {");
lines.push("  font-variant-numeric: tabular-nums;");
lines.push('  font-feature-settings: "tnum" 1;');
lines.push("}");
lines.push("");
lines.push(".bg-signal-gradient {");
lines.push("  background-image: var(--gradient-signal);");
lines.push("}");
lines.push("");

const content = lines.join("\n");
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content, "utf8");
console.log(`Generated ${path.relative(webDir, outPath)} (${themeColorNames.length} color tokens).`);
