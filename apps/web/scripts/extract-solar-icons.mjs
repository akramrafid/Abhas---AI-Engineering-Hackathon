const missing = [];
const data = {};
for (const [key, solarName] of Object.entries(MAP)) {
  const icon = solar.icons[solarName];
  if (!icon) {
    missing.push(`${key}:${solarName}`);
  } else {
    data[key] = { body: icon.body, width: icon.width || 24, height: icon.height || 24 };
  }
}

if (missing.length > 0) {
  console.error("Missing Solar Bold Duotone icons:", missing);
  process.exit(1);
}

const outDir = path.resolve("src/components/icons");
fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, "solar-data.ts");
const content = [
  "/* AUTO-GENERATED by scripts/extract-solar-icons.mjs from @iconify-json/solar (Solar Bold Duotone). */",
  'import type { IconifyIcon } from "@iconify/react";',
  "",
  `export const SOLAR_ICONS = ${JSON.stringify(data, null, 2)} as const satisfies Record<string, IconifyIcon>;`,
  "",
  "export type SolarIconKey = keyof typeof SOLAR_ICONS;",
  "",
].join("\n");

fs.writeFileSync(outFile, content, "utf8");
console.log(`Wrote ${Object.keys(data).length} Solar Bold Duotone icons -> ${outFile}`);
